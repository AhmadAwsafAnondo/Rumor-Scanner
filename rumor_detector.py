import io


def extract_ela_features(
    path,
    quality=90
):

    original = Image.open(
        path
    ).convert("RGB")

    buffer = io.BytesIO()

    original.save(
        buffer,
        format="JPEG",
        quality=quality
    )

    buffer.seek(0)

    recompressed = Image.open(
        buffer
    ).convert("RGB")

    original_array = np.asarray(
        original,
        dtype=np.float32
    )

    recompressed_array = np.asarray(
        recompressed,
        dtype=np.float32
    )

    difference = np.abs(
        original_array
        -
        recompressed_array
    )

    ela_mean = np.mean(
        difference
    )

    ela_std = np.std(
        difference
    )

    ela_max = np.max(
        difference
    )


    high_error_ratio = np.mean(
        difference > 20
    )

    return [
        ela_mean,
        ela_std,
        ela_max,
        high_error_ratio
    ]

def extract_noise_features(path):

    image = load_image(path)

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    gray = gray.astype(
        np.float32
    )

    blurred = cv2.GaussianBlur(
        gray,
        (5, 5),
        0
    )

    residual = (
        gray - blurred
    )

    noise_mean = np.mean(
        np.abs(residual)
    )

    noise_std = np.std(
        residual
    )

    return [
        noise_mean,
        noise_std
    ]

def extract_laplacian_features(path):

    image = load_image(path)

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    laplacian = cv2.Laplacian(
        gray,
        cv2.CV_64F
    )

    lap_variance = np.var(
        laplacian
    )

    lap_mean_abs = np.mean(
        np.abs(laplacian)
    )

    return [
        lap_variance,
        lap_mean_abs
    ]

