def extract_ela_features(path, quality=90):

    with Image.open(path) as img:

        original = img.convert("RGB")

        buffer = io.BytesIO()

        original.save(
            buffer,
            format="JPEG",
            quality=quality
        )

        buffer.seek(0)

        compressed = Image.open(
            buffer
        ).convert("RGB")

        original_array = np.array(
            original,
            dtype=np.float32
        )

        compressed_array = np.array(
            compressed,
            dtype=np.float32
        )


    diff = np.abs(
        original_array
        -
        compressed_array
    )


    return [
        float(np.mean(diff)),
        float(np.std(diff)),
        float(np.max(diff)),
        float(np.mean(diff > 20))
    ]


