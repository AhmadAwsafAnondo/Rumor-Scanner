def perform_ela(image_path, quality=90):

    original = Image.open(
        image_path
    ).convert("RGB")

    temp_path = "/content/temp_ela.jpg"

    original.save(
        temp_path,
        "JPEG",
        quality=quality
    )

    recompressed = Image.open(
        temp_path
    ).convert("RGB")

    difference = ImageChops.difference(
        original,
        recompressed
    )

    extrema = difference.getextrema()

    max_difference = max(
        value[1]
        for value in extrema
    )

    if max_difference == 0:
        max_difference = 1

    scale = 255.0 / max_difference

    ela_image = ImageEnhance.Brightness(
        difference
    ).enhance(scale)

    return ela_image

