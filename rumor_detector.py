def block_sharpness_map(
    image_path,
    block_size=64
):

    image = cv2.imread(
        image_path,
        cv2.IMREAD_GRAYSCALE
    )

    height, width = image.shape

    rows = height // block_size
    cols = width // block_size

    sharpness_map = np.zeros(
        (rows, cols)
    )

    for row in range(rows):

        for col in range(cols):

            y1 = row * block_size
            y2 = y1 + block_size

            x1 = col * block_size
            x2 = x1 + block_size

            block = image[
                y1:y2,
                x1:x2
            ]

            lap = cv2.Laplacian(
                block,
                cv2.CV_64F
            )

            sharpness_map[
                row,
                col
            ] = lap.var()

    return sharpness_map

